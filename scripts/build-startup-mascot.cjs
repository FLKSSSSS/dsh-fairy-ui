'use strict';
// Reuse the conversation's actual SVG, CSS, clock, expressions and fault engine.
// Namespace only DOM/CSS/SVG identities so preview never steals the chat mascot.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),clientFile=path.join(root,'lib/client.js');
let client=fs.readFileSync(clientFile,'utf8').replace(/\r\n/g,'\n');
const uniqueIndex=(source, marker)=>{
 const at=source.indexOf(marker);
 if(at<0||source.indexOf(marker,at+marker.length)>=0)throw Error('Expected exactly one marker: '+marker.trim());
 return at;
};
const names=['mascot-style','mascot-geometry','mascot-effects-svg','mascot-eye-svg','mascot-assets','mascot-motion-clock','mascot-event-scheduler','mascot-runtime'];
const regions=names.map(name=>{
 const start=client.indexOf('//#region src/client/'+name+'.js'),end=client.indexOf('//#endregion',start);
 if(start<0||end<0)throw Error('Missing conversation mascot source: '+name);
 return client.slice(start,end).replaceAll('dsh-fairy-','dsh-fairy-startup-');
}).join('\n');
const header=`/* Generated by scripts/build-startup-mascot.cjs from the conversation mascot. Do not hand-edit. */
(() => {
const __commonJSMin=cb=>{let m;return()=>{if(!m){m={exports:{}};cb(m.exports,m)}return m.exports}};
const require_dom_observer_manager=()=>({createManagedMutationObserver:callback=>new MutationObserver(callback)});
`;
const runtime=header+regions;
const context={};vm.runInNewContext(runtime+';globalThis.assets=require_mascot_assets();})();',context);
const css=context.assets.CSS+`\n[data-dsh-fairy-startup-mascot-root="true"]{width:100%!important;height:100%!important;pointer-events:none!important}\n`;
const wrapper=`
const STARTUP_CSS=${JSON.stringify(css)};
globalThis.FairyStartupMascot = Object.freeze({
 mount(stage) {
  if(!document.getElementById('dsh-fairy-startup-mascot-style')){
   const style=document.createElement('style');style.id='dsh-fairy-startup-mascot-style';style.textContent=STARTUP_CSS;document.head.appendChild(style);
  }
  const runtime=require_mascot_runtime().createMascotRuntime();
  const owner={stage,active:true};
  stage.classList.add('dsh-fairy-startup-stage');
  stage.setAttribute('data-fairy-visual-active','true');
  stage.setAttribute('data-fairy-state','normal');
  runtime.mount(stage,owner,1);
  let disposed=false;
  return {
   freeze(){if(!disposed)runtime.setVisualActive(false,owner)},
   dispose(){if(disposed)return;disposed=true;runtime.dispose(owner);stage.classList.remove('dsh-fairy-startup-stage')}
  };
 }
});
})();\n`;
const code=runtime+wrapper;
fs.writeFileSync(path.join(root,'desktop-startup/startup-mascot.js'),code);
fs.writeFileSync(path.join(root,'desktop-startup/startup-mascot.css'),css);
// The pre-mount fallback must also have private SVG identities in web previews.
const skinFile=path.join(root,'desktop-startup/startup-skin.js');
const skinSource=fs.readFileSync(skinFile,'utf8').replace(/\r\n/g,'\n');
if((skinSource.match(/ const EYE = .*;\n/g)||[]).length!==1)throw Error('Expected one startup fallback eye');
const skin=skinSource.replace(/ const EYE = .*;\n/, ()=>' const EYE = '+JSON.stringify(context.assets.SVG)+';\n');
fs.writeFileSync(skinFile,skin);
const skinBegin='// BEGIN SHARED STARTUP SKIN\n',skinEnd='// END SHARED STARTUP SKIN';
client=client.slice(0,uniqueIndex(client,skinBegin))+skinBegin+skin+client.slice(uniqueIndex(client,skinEnd));
const begin='// BEGIN SHARED STARTUP MASCOT\n',end='// END SHARED STARTUP MASCOT';
if(client.includes(begin))client=client.slice(0,uniqueIndex(client,begin))+begin+code+end+client.slice(uniqueIndex(client,end)+end.length);
else {const at=client.indexOf('// BEGIN SHARED STARTUP SKIN');if(at<0)throw Error('Missing startup preview');client=client.slice(0,at)+begin+code+end+'\n'+client.slice(at)}
new vm.Script(client,{filename:clientFile});
fs.writeFileSync(clientFile,client);
console.log('Built namespaced startup mascot from 8 unmodified conversation modules.');
